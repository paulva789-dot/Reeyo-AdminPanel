// Interface strings — specification §2.1.
//
// The key is the English text itself. Two reasons, both about failure modes:
//
//   1. A missing entry falls through to correct English. With symbolic keys a
//      gap renders as `nav.orders` in the middle of the interface, which is a
//      worse bug than the one it was meant to catch.
//   2. Retrofitting is a wrap, not a rename. `header: 'Customer'` becomes
//      `header: t('Customer')`, and nothing has to be kept in step by hand.
//
// What is deliberately NOT here: vendor names, item names, customer names,
// addresses and zone names. §2.1 is explicit that entered data stays exactly as
// entered — a console that "translated" Carrefour Obili would be worse than one
// that translated nothing.

