/**
 * Translates interface text. The input is the English string, so anything the
 * dictionary has not caught up with still reads correctly.
 */
export function translate(
  language: Language,
  text: string,
  vars?: Record<string, string | number>,
): string {
  let out = language === 'fr' ? (FRENCH[text] ?? text) : text;
  if (vars) {
    for (const [name, value] of Object.entries(vars)) {
      out = out.replace(new RegExp(`\\{${name}\\}`, 'g'), String(value));
    }
  }
  return out;
}
